"""Timing from the supplied voiceover: vo/words.json + timeline.json -> src/shared/timing.ts

The narration is the clock. Every scene starts on the first word of a phrase,
every cue lands on a spoken word, and nothing is a typed frame number.

timeline.json
  {
    "fps": 30, "transition": 14, "tail": 75,
    "scenes": [{"name": "hook", "at": "10"}, {"name": "brain", "at": "you know theyre"}, ...],
    "cues": {
      "hook.tag10": "10",                         phrase, first word
      "hook.stamp": {"at": "one cent", "off": -4}  shifted (frames)
      "hook.end":   {"at": "apart", "word": "end"} when the word finishes
    }
  }

Phrases are matched on normalised tokens (lowercase letters and digits only),
searched from the start of the cue's own scene, so repeats resolve correctly.

    python3 vo/build_timing.py            write src/shared/timing.ts + vo/scenes.txt
    python3 vo/build_timing.py --check    print the table only
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
norm = lambda s: re.sub(r"[^a-z0-9]", "", s.lower())

words = json.loads((ROOT / "vo/words.json").read_text())
W = [dict(w, n=norm(w["w"])) for w in words["words"]]
W = [w for w in W if w["n"]]
spec = json.loads((ROOT / "timeline.json").read_text())
FPS, T, TAIL = spec["fps"], spec["transition"], spec["tail"]
TOTAL = words["duration"]


def find(phrase: str, start: int = 0, stop: int | None = None) -> int:
    toks = [norm(t) for t in phrase.split() if norm(t)]
    stop = len(W) if stop is None else stop
    for i in range(start, stop - len(toks) + 1):
        if all(W[i + k]["n"] == toks[k] for k in range(len(toks))):
            return i
    ctx = " ".join(w["n"] for w in W[start:min(stop, start + 60)])
    raise SystemExit(f"phrase not found: '{phrase}' (searching from word {start}: {ctx} ...)")


# scene boundaries: just before the scene's first word, inside the gap
scenes = spec["scenes"]
idx, starts = [], []
cursor = 0
for i, sc in enumerate(scenes):
    k = 0 if i == 0 else find(sc["at"], cursor)
    idx.append(k)
    cursor = k + 1
    t = 0.0 if i == 0 else max(W[k - 1]["e"], W[k]["t"] - 0.22)
    starts.append(round(t * FPS))
end_frame = round(TOTAL * FPS) + TAIL
durs = [(starts[i + 1] if i + 1 < len(scenes) else end_frame) - starts[i] for i in range(len(scenes))]
names = [s["name"] for s in scenes]

# cues, scene-local
cues = {}
for key, c in spec["cues"].items():
    c = {"at": c} if isinstance(c, str) else c
    sc = key.split(".")[0]
    if sc not in names:
        raise SystemExit(f"cue '{key}': no scene '{sc}'")
    i = names.index(sc)
    stop = idx[i + 1] if i + 1 < len(scenes) else len(W)
    k = find(c["at"], idx[i], stop)
    toks = [t for t in c["at"].split() if norm(t)]
    w = W[k + len(toks) - 1] if c.get("word") == "end" else W[k]
    t = w["e"] if c.get("word") == "end" else w["t"]
    f = round(t * FPS) - starts[i] + int(c.get("off", 0))
    if not (0 <= f < durs[i]):
        raise SystemExit(f"cue '{key}' at local frame {f} is outside scene '{sc}' (0..{durs[i]})")
    cues[key] = f

# reference sheet: every scene's words with local frames, for authoring cues
lines = []
for i, sc in enumerate(scenes):
    stop = idx[i + 1] if i + 1 < len(scenes) else len(W)
    ws = " ".join(f"{w['w']}@{round(w['t'] * FPS) - starts[i]}" for w in W[idx[i]:stop])
    lines.append(f"{i + 1:>2} {sc['name']:<12} start {starts[i]:>5}  {durs[i]:>4}f {durs[i] / FPS:5.1f}s | {ws}")

if "--check" in sys.argv:
    print("\n".join(l[:180] for l in lines))
    sys.exit()

(ROOT / "vo/scenes.txt").write_text("\n".join(lines) + "\n")
ts = [
    "// GENERATED by vo/build_timing.py from vo/words.json + timeline.json. Do not hand-edit.",
    "",
    f"export const FPS = {FPS};",
    "/** Frames each scene pushes over the previous one. Every scene but the last is",
    " *  lengthened by T so that, with the overlap, it still starts on its word. */",
    f"export const T = {T};",
    "",
    "/** Scene lengths (word to word, before the transition overlap). */",
    "export const D = {",
    *[f"  {n}: {d}," for n, d in zip(names, durs)],
    "} as const;",
    "",
    "export const SCENE_ORDER = [" + ", ".join(f'"{n}"' for n in names) + "] as const;",
    f"export const SEQUENCE_DURATION = {end_frame};",
    "",
    "/** Scene-local frames, each on a spoken word. */",
    "export const CUE = {",
    *[f'  "{k}": {v},' for k, v in sorted(cues.items())],
    "} as const;",
    "",
]
(ROOT / "src/shared/timing.ts").write_text("\n".join(ts))
print(f"{len(scenes)} scenes, {len(cues)} cues, {end_frame} frames ({end_frame / FPS:.1f}s)")
